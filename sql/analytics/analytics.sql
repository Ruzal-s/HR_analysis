SELECT COUNT(CASE WHEN EMPID IS NULL THEN 1 END) FROM HR;
/*DISTINCT VALUES*/
SELECT COUNT(*) FROM (SELECT DISTINCT * FROM HR);
/*INVALID VALUES*/
SELECT COUNT(CASE WHEN GENDER IN ('Male','Female') THEN 1 END) FROM HR;
