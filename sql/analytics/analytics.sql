/*<==========SALARY ANALYSIS==========>*/

/*AVG SALARY BY DEPT*/
SELECT Department, ROUND(AVG(MonthlyIncome),0) AS AVG_SALARY FROM HR
GROUP BY Department;
/*HIGHEST SALARY*/
SELECT Department,MAX(MONTHLYINCOME) AS HIGHEST_SALARY FROM HR;
/*LOWEST SALARY*/
SELECT Department,MIN(MONTHLYINCOME) AS LOWEST_SALARY FROM HR;

/*TOP 10 HIGHEST PAID EMPLOYEES*/
SELECT Department,MONTHLYINCOME FROM HR
ORDER BY MONTHLYINCOME DESC
LIMIT 10;
/*SALARY RANKING*/
SELECT * FROM (SELECT Department,MonthlyIncome,
RANK() OVER(ORDER BY MONTHLYINCOME) AS RNK FROM HR
GROUP BY Department)
WHERE RNK<=3;
/*SALARY QUARTILES*/
SELECT * FROM
(SELECT EMPID,DEPARTMENT,NTILE(4) OVER(ORDER BY MonthlyIncome) AS SALARY_QUARTILE FROM HR)
WHERE EMPID='';


