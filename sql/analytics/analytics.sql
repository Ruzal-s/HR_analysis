PRAGMA table_info(HR);
/*TOTAL EMPLOYEES*/
SELECT COUNT(DISTINCT EmpID) AS total_employees FROM HR;
/*TOTAL DEPARTMENTS*/
SELECT COUNT(DISTINCT Department) AS total_departments FROM HR;
/*TOTAL JOB ROLES*/
SELECT COUNT(DISTINCT JobRole) AS total_Job_Roles FROM HR;
/*TOTAL EDUCATION FIELDS*/
SELECT COUNT(DISTINCT EducationField) AS total_Education_fields FROM HR;
/*TOTAL BUSINESS TRAVEL TYPES*/
SELECT COUNT(DISTINCT BusinessTravel) AS total_business_travel_types FROM HR;
/*AGE RANGE*/
SELECT CONCAT(MIN(Age)||'-'||MAX(Age)) AS age_range FROM HR;
/*SALARY RANGE*/
SELECT CONCAT(MIN(MonthlyIncome)||'-'||MAX(MonthlyIncome)) AS salary_range FROM HR;
/*YEARS AT COMPANY RANGE*/
SELECT CONCAT(MIN(YearsAtCompany)||'-'||MAX(YearsAtCompany)) AS years_at_company_range FROM HR;


